def normalize_language(value: str | None, default: str = "en") -> str:
    if not value:
        return default
    value = value.lower().split("-")[0]
    return value if value in TRANSLATIONS else default


def translator(language: str) -> Mapping[str, str]:
    return TRANSLATIONS[normalize_language(language)]
